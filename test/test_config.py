class TestResolveHostname:
    """Tests for hostname resolution based on request URL."""
    
    def test_localhost_allows_custom_header(self):
        """Localhost requests allow any X-ViaFoundry-Hostname value."""
        hostname, is_localhost = resolve_hostname(
            header_hostname="https://custom.viafoundry.com",
            request_scheme="http",
            request_host="127.0.0.1:8000",
            request_path="/mcp"
        )
        assert hostname == "https://custom.viafoundry.com"
        assert is_localhost is True
    
    def test_localhost_returns_none_without_header(self):
        """Localhost requests return None if no header provided."""
        hostname, is_localhost = resolve_hostname(
            header_hostname=None,
            request_scheme="http",
            request_host="localhost:8000",
            request_path="/mcp"
        )
        assert hostname is None
        assert is_localhost is True
    
    def test_production_strips_mcp_suffix(self):
        """Production requests strip /mcp suffix from hostname."""
        hostname, is_localhost = resolve_hostname(
            header_hostname="https://custom.viafoundry.com",  # Should be ignored
            request_scheme="https",
            request_host="mcp.viafoundry.com",
            request_path="/mcp"
        )
        assert hostname == "https://mcp.viafoundry.com"
        assert is_localhost is False
    
    def test_production_keeps_prefix_path(self):
        """Production requests keep path prefix before /mcp."""
        hostname, is_localhost = resolve_hostname(
            header_hostname="https://custom.viafoundry.com",  # Should be ignored
            request_scheme="https",
            request_host="dev-playground.infra.gcp.viafoundry.net",
            request_path="/beta/mcp"
        )
        assert hostname == "https://dev-playground.infra.gcp.viafoundry.net/beta"
        assert is_localhost is False
    
    def test_production_ignores_header(self):
        """Production requests ignore X-ViaFoundry-Hostname header."""
        hostname, is_localhost = resolve_hostname(
            header_hostname="https://malicious.site.com",  # Must be ignored
            request_scheme="https",
            request_host="prod.viafoundry.com",
            request_path="/mcp"
        )
        assert hostname == "https://prod.viafoundry.com"
        assert is_localhost is False
    
    def test_production_works_without_header(self):
        """Production requests work without header."""
        hostname, is_localhost = resolve_hostname(
            header_hostname=None,
            request_scheme="https",
            request_host="prod.viafoundry.com",
            request_path="/mcp"
        )
        assert hostname == "https://prod.viafoundry.com"
        assert is_localhost is False
    
    def test_localhost_with_port(self):
        """Localhost with port should work."""
        hostname, is_localhost = resolve_hostname(
            header_hostname="https://my-viafoundry.com",
            request_scheme="http",
            request_host="0.0.0.0:8000",
            request_path="/mcp"
        )
        assert hostname == "https://my-viafoundry.com"
        assert is_localhost is True
    
    def test_production_preserves_port(self):
        """Production hostname preserves port if present."""
        hostname, is_localhost = resolve_hostname(
            header_hostname=None,
            request_scheme="https",
            request_host="prod.viafoundry.com:8443",
            request_path="/mcp"
        )
        assert hostname == "https://prod.viafoundry.com:8443"
        assert is_localhost is False
