class TestIsLocalhostRequest:
    """Tests for localhost detection."""
    
    def test_localhost_hosts_detected(self):
        """Test that all localhost hosts are detected."""
        for host in LOCALHOST_HOSTS:
            assert is_localhost_request(host) is True, f"{host} should be localhost"
    
    def test_localhost_with_port_detected(self):
        """Test that localhost with port is detected."""
        assert is_localhost_request("127.0.0.1:8000") is True
        assert is_localhost_request("localhost:8000") is True
        assert is_localhost_request("0.0.0.0:8000") is True
    
    def test_production_hosts_not_localhost(self):
        """Test that production hosts are not localhost."""
        production_hosts = [
            "viafoundry.com",
            "mcp.viafoundry.com",
            "192.168.1.1",
            "10.0.0.1:8000",
            "example.com:443",
        ]
        for host in production_hosts:
            assert is_localhost_request(host) is False, f"{host} should not be localhost"
    
    def test_empty_host_not_localhost(self):
        """Test that empty host is not localhost."""
        assert is_localhost_request("") is False
        assert is_localhost_request(None) is False


class TestBuildHostnameFromRequest:
    """Tests for hostname building (with /mcp suffix trimmed)."""
    
    def test_build_hostname_strips_mcp(self):
        """Test that /mcp suffix is stripped."""
        url = build_hostname_from_request("https", "example.com", "/mcp")
        assert url == "https://example.com"
    
    def test_build_hostname_keeps_prefix_path(self):
        """Test that prefix path before /mcp is kept."""
        url = build_hostname_from_request("https", "example.com", "/beta/mcp")
        assert url == "https://example.com/beta"
    
    def test_build_hostname_complex_path(self):
        """Test with more complex path prefix."""
        url = build_hostname_from_request("https", "dev-playground.infra.gcp.viafoundry.net", "/beta/mcp")
        assert url == "https://dev-playground.infra.gcp.viafoundry.net/beta"
    
    def test_build_hostname_no_path(self):
        """Test with no path."""
        url = build_hostname_from_request("https", "example.com")
        assert url == "https://example.com"
    
    def test_build_hostname_with_port(self):
        """Test building hostname with port."""
        url = build_hostname_from_request("http", "localhost:8000", "/mcp")
        assert url == "http://localhost:8000"
    
    def test_build_hostname_non_mcp_path(self):
        """Test that non-mcp paths are kept as-is."""
        url = build_hostname_from_request("https", "example.com", "/api/v1")
        assert url == "https://example.com/api/v1"


